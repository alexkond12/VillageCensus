def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "common", "src", "main", "resources", "assets", "villagecensus", "lang")
    os.makedirs(out, exist_ok=True)
    for lang, values in T.items():
        assert len(values) == len(KEYS), f"{lang}: {len(values)} values for {len(KEYS)} keys"
        for k, v, e in zip(KEYS, values, T["en_us"]):
            assert v.count("%s") == e.count("%s"), f"{lang} {k}: placeholder count differs"
        with open(os.path.join(out, lang + ".json"), "w", encoding="utf-8", newline="\n") as f:
            json.dump(dict(zip(KEYS, values)), f, ensure_ascii=False, indent=2)
            f.write("\n")
    print(f"Wrote {len(T)} language files with {len(KEYS)} keys each to {os.path.normpath(out)}")

if __name__ == "__main__":
    main()
